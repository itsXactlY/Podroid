#!/bin/sh
# configure.sh — write Ariadne's config.yaml from pod.env.
#
# pod.env holds what reaches the pod at runtime: the model (pushed by the app's
# /agent-config) and the MCP proxy URL (the guest's default gateway, port 8790).
# mcp-mazemaker-watch.sh writes it; this turns it into the file Ariadne reads.
#
# The first line of a generated config.yaml is the marker below. A config.yaml
# without it is the operator's own and is never rewritten: delete the marker
# line to keep hand edits.
#
# With nothing pushed yet the model is OpenRouter's free tier with no key, the
# same default the image shipped before; chat answers 401 until a key arrives.
ARIADNE_HOME="${ARIADNE_HOME:-/opt/ariadne/home}"
CONFIG="$ARIADNE_HOME/config.yaml"
POD_ENV="$ARIADNE_HOME/pod.env"
MARK="# generated by /opt/ariadne/configure.sh from pod.env; delete this line to keep your own edits"

if [ -f "$CONFIG" ] && [ "$(head -n 1 "$CONFIG")" != "$MARK" ]; then
    exit 0
fi

MODEL_BASE_URL="https://openrouter.ai/api/v1"
MODEL_NAME="tencent/hy3:free"
MODEL_API_KEY=""
MCP_URL=""
# pod.env is written by the watcher with every value single-quoted, so sourcing
# it assigns strings and runs nothing.
[ -f "$POD_ENV" ] && . "$POD_ENV"

# YAML double-quoted scalar: backslash and quote escaped, nothing else special.
q() { printf '"%s"' "$(printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g')"; }

mkdir -p "$ARIADNE_HOME"
tmp="$CONFIG.tmp.$$"
(
    umask 077
    {
        echo "$MARK"
        echo "model:"
        echo "  base_url: $(q "$MODEL_BASE_URL")"
        echo "  name: $(q "$MODEL_NAME")"
        echo "  api_key: $(q "$MODEL_API_KEY")"
        if [ -n "$MCP_URL" ]; then
            echo "mcp_servers:"
            echo "  mazemaker:"
            echo "    enabled: true"
            echo "    transport: http"
            echo "    url: $(q "$MCP_URL")"
            echo "    instructions: harness"
            echo "    tools:"
            echo "      mazemaker_prune: {enabled: false}"
        fi
    } > "$tmp"
) && mv "$tmp" "$CONFIG"
